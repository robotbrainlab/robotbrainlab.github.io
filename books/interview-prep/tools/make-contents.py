#!/usr/bin/env python3
"""Build CONTENTS.md: the plan and the real section headings together.

`TOC.md` is the plan - one row per chapter, with its opening problem and
its Covers list - and it has no section headings in it, because the
sections do not exist until the chapter is written. The built `book.pdf`
has the real headings and none of the plan. This puts both in one file,
so a chapter reads as: what it is for, what it must cover, and what it
actually says.

    python3 tools/make-contents.py

Writes CONTENTS.md in _book/. It is generated - edit TOC.md or a chapter
and run this again. Headings are taken only from outside fenced blocks,
because a `#` comment inside a program is not a section.
"""
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ROW = re.compile(r"^\|\s*(\d+)\s*\|\s*([^|]+?)\s*\|\s*([^|]*?)\s*\|"
                 r"\s*([^|]*?)\s*\|\s*(\d+)\s*\|")
APP = re.compile(r"^\|\s*([A-D])\s*\|\s*([^|]+?)\s*\|"
                 r"\s*([^|]*?)\s*\|\s*(\d+)\s*\|", re.M)

def parts():
    """TOC.md's chapter rows, grouped under the part heading above them."""
    out, head = [], None
    for line in (ROOT / "TOC.md").read_text(encoding="utf-8").splitlines():
        if line.startswith("## "):
            head = line[3:].strip()
            if head.startswith(("Who owns", "Writing and")):
                head = None
        m = ROW.match(line)
        if m and head:
            n, title, problem, covers, pages = m.groups()
            out.append((head, int(n), title, problem, covers, int(pages)))
    return out

def headings(path):
    """A chapter's `##` headings, skipping anything inside a fence."""
    found, in_fence = [], False
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
        elif not in_fence and line.startswith("## "):
            found.append(line[3:].strip())
    return found

def printed_pages():
    """Each chapter's printed page range, from tools/pages.py."""
    out = {}
    try:
        txt = subprocess.run(["python3", str(ROOT / "tools" / "pages.py")],
                             capture_output=True, text=True,
                             cwd=ROOT).stdout
    except OSError:
        return out
    for line in txt.splitlines():
        f = line.split()
        if len(f) >= 3 and f[0].isdigit():
            out[int(f[0])] = (f[1], int(f[2]))
    return out

def main():
    rows = parts()
    pages = printed_pages()
    files = {int(p.name[:2]): p
             for p in sorted((ROOT / "markdown").glob("[0-9][0-9]-*.md"))}
    written = sorted(n for n in files if n in {r[1] for r in rows})

    L = ["# Contents", "",
         "*Generated by `python3 tools/make-contents.py`. The plan comes "
         "from `TOC.md`; the sub-headings are read out of the chapters "
         "themselves, so a chapter has them only once it is written.*", "",
         f"**{len(written)} of {len(rows)} chapters written.** A written "
         "chapter shows its printed pages and its sections. A planned one "
         "shows its page estimate and its Covers list, which is the "
         "nearest thing it has to sections.", ""]

    seen = None
    for head, n, title, problem, covers, est in rows:
        if head != seen:
            L += [f"## {head}", ""]
            seen = head
        if n in files:
            rng, pp = pages.get(n, ("-", 0))
            L.append(f"### {n}. {title}")
            L.append(f"*Written — pages {rng}, {pp} printed "
                     f"(estimate {est}).*")
            L.append("")
            L.append(f"> {problem}")
            L.append("")
            for h in headings(files[n]):
                L.append(f"- {h}")
            L.append("")
        else:
            L.append(f"### {n}. {title}")
            L.append(f"*Planned — estimate {est} pp.*")
            L.append("")
            L.append(f"> {problem}")
            L.append("")
            L.append(f"Covers: {covers}")
            L.append("")

    files_app = {p.name[0]: p
                 for p in sorted((ROOT / "markdown").glob("[A-Z]-*.md"))}
    planned_app = APP.findall(
        (ROOT / "TOC.md").read_text(encoding="utf-8"))
    L += ["## Appendices", ""]
    for letter, title, covers, est in planned_app:
        L.append(f"### {letter}. {title}")
        if letter in files_app:
            L.append(f"*Written — estimate {est} pp.*")
            L.append("")
            hs = headings(files_app[letter])
            for h in hs:
                L.append(f"- {h}")
            if not hs:
                L.append("*One list, no sections.*")
        else:
            L.append(f"*Planned — estimate {est} pp. {covers}*")
        L.append("")

    L += ["## Also in `TOC.md`", "",
          "- **Who owns what** — the concept-ownership table. One chapter "
          "owns each concept; every other refers to it by number and does "
          "not re-teach it.",
          "- **Writing and delivery order** — which part is built and "
          "handed over when, and why in that order.", ""]

    (ROOT / "CONTENTS.md").write_text("\n".join(L), encoding="utf-8")
    print(f"CONTENTS.md: {len(rows)} chapters, {len(written)} written, "
          f"{len(files_app)} of {len(planned_app)} appendices present")

if __name__ == "__main__":
    main()
